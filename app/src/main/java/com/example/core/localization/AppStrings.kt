enum class AppLanguage(
    val code: String,
    val nativeName: String,
    val shortCode: String,
    val layoutDirection: LayoutDirection
) {
    AR("ar", "العربية", "AR", LayoutDirection.Rtl),
    EN("en", "English", "EN", LayoutDirection.Ltr),
    FA("fa", "فارسی", "FA", LayoutDirection.Rtl),
    RU("ru", "Русский", "RU", LayoutDirection.Ltr),
    IT("it", "Italiano", "IT", LayoutDirection.Ltr),
    UR("ur", "اردو", "UR", LayoutDirection.Rtl),
    ZH("zh", "中文", "ZH", LayoutDirection.Ltr);

    val isRtl: Boolean get() = layoutDirection == LayoutDirection.Rtl

    companion object {
        fun fromCode(code: String?): AppLanguage =
            entries.firstOrNull { it.code.equals(code, ignoreCase = true) } ?: AR
    }
}

